create or replace function public.leaderboard(p_limit integer default 10)
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
    with top as (
        select
            m.username,
            m.matches,
            m.attributes,
            p.avatar_url,
            p.character_id
        from public.player_models m
        left join public.profiles p on p.id = m.auth_uid
        order by m.matches desc, m.username asc
        limit least(greatest(coalesce(p_limit, 10), 1), 100)
    )
    select coalesce(
        jsonb_agg(
            jsonb_build_object(
                'username', username,
                'matches', matches,
                'pattern', coalesce((attributes->>'pattern')::numeric, 0),
                'avatar_url', avatar_url,
                'character_id', character_id
            )
            order by matches desc, username asc
        ),
        '[]'::jsonb
    )
    from top;
$$;

revoke all on function public.leaderboard(integer) from public, anon, authenticated;
grant execute on function public.leaderboard(integer) to service_role;
