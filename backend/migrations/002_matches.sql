create table if not exists public.matches (
    id bigint generated by default as identity primary key,
    room text not null,
    seed bigint,
    winner integer not null default 0,
    cycles integer not null default 0,
    rounds integer not null default 0,
    duration numeric(10, 2) not null default 0,
    team_skill numeric(8, 5) not null default 0,
    difficulty numeric(8, 5) not null default 0,
    eliminated integer not null default 0,
    created_at timestamptz not null default now(),
    summary jsonb not null default '{}'::jsonb
);

create index if not exists matches_created_at_idx
    on public.matches (created_at desc);

create table if not exists public.match_players (
    id bigint generated by default as identity primary key,
    match_id bigint not null references public.matches(id) on delete cascade,
    auth_uid text,
    username text,
    slot integer,
    escaped boolean not null default false,
    eliminated boolean not null default false,
    points integer not null default 0,
    revives integer not null default 0,
    predictions integer not null default 0,
    correct integer not null default 0,
    attributes jsonb not null default '{}'::jsonb
);

create index if not exists match_players_match_id_idx
    on public.match_players (match_id);
create index if not exists match_players_auth_uid_idx
    on public.match_players (auth_uid);

create table if not exists public.player_models (
    auth_uid text primary key,
    username text not null,
    attributes jsonb not null default '{}'::jsonb,
    style text,
    matches integer not null default 0,
    updated_at timestamptz not null default now()
);

create index if not exists player_models_matches_idx
    on public.player_models (matches desc);

alter table public.matches enable row level security;
alter table public.match_players enable row level security;
alter table public.player_models enable row level security;

revoke all on public.matches, public.match_players, public.player_models from anon, authenticated;
grant select, insert, update, delete on public.matches, public.match_players, public.player_models to service_role;

create or replace function public.record_match(p_summary jsonb)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
    v_match_id bigint;
    v_player jsonb;
    v_uid text;
    v_name text;
begin
    insert into public.matches (
        room, seed, winner, cycles, rounds, duration, team_skill, difficulty,
        eliminated, summary
    )
    values (
        coalesce(p_summary->>'room', ''),
        coalesce((p_summary->>'seed')::bigint, 0),
        coalesce((p_summary->>'winner')::integer, 0),
        coalesce((p_summary->>'cycles')::integer, 0),
        coalesce((p_summary->>'rounds')::integer, 0),
        coalesce((p_summary->>'duration')::numeric, 0),
        coalesce((p_summary->>'team_skill')::numeric, 0),
        coalesce((p_summary->>'difficulty')::numeric, 0),
        coalesce((p_summary->>'eliminated')::integer, 0),
        coalesce(p_summary, '{}'::jsonb)
    )
    returning id into v_match_id;

    for v_player in
        select value from jsonb_array_elements(coalesce(p_summary->'players', '[]'::jsonb))
    loop
        v_uid := nullif(btrim(coalesce(v_player->>'uid', '')), '');
        if v_uid is null or not coalesce((v_player->>'verified')::boolean, false) then
            continue;
        end if;

        v_name := nullif(btrim(coalesce(v_player->>'name', '')), '');

        insert into public.match_players (
            match_id, auth_uid, username, slot, escaped, eliminated, points,
            revives, predictions, correct, attributes
        )
        values (
            v_match_id,
            v_uid,
            coalesce(v_name, 'Player'),
            coalesce((v_player->>'slot')::integer, 0),
            coalesce((v_player->>'escaped')::boolean, false),
            coalesce((v_player->>'eliminated')::boolean, false),
            coalesce((v_player->>'points')::integer, 0),
            coalesce((v_player->>'revives')::integer, 0),
            coalesce((v_player->>'predictions')::integer, 0),
            coalesce((v_player->>'correct')::integer, 0),
            coalesce(v_player->'attrs', '{}'::jsonb)
        );

        insert into public.player_models (
            auth_uid, username, attributes, style, matches, updated_at
        )
        values (
            v_uid,
            coalesce(v_name, 'Player'),
            coalesce(v_player->'attrs', '{}'::jsonb),
            nullif(btrim(coalesce(v_player->>'style', '')), ''),
            1,
            now()
        )
        on conflict (auth_uid) do update set
            username = excluded.username,
            attributes = excluded.attributes,
            style = excluded.style,
            matches = public.player_models.matches + 1,
            updated_at = now();
    end loop;

    return v_match_id;
end;
$$;

create or replace function public.match_history(p_uid text, p_limit integer default 20)
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
    with recent as (
        select m.*
        from public.matches m
        where exists (
            select 1 from public.match_players mp
            where mp.match_id = m.id and mp.auth_uid = p_uid
        )
        order by m.created_at desc
        limit least(greatest(coalesce(p_limit, 20), 1), 100)
    )
    select coalesce(
        jsonb_agg(
            jsonb_build_object(
                'id', id,
                'room', room,
                'seed', seed,
                'winner', winner,
                'cycles', cycles,
                'rounds', rounds,
                'duration', duration,
                'team_skill', team_skill,
                'difficulty', difficulty,
                'created_at', extract(epoch from created_at),
                'summary', summary
            )
            order by created_at desc
        ),
        '[]'::jsonb
    )
    from recent;
$$;

create or replace function public.player_stats(p_uid text, p_username text default null)
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
    with totals as (
        select
            count(*)::integer as matches,
            coalesce(sum(case when escaped then 1 else 0 end), 0)::integer as escapes,
            coalesce(sum(predictions), 0)::integer as predictions,
            coalesce(sum(correct), 0)::integer as correct
        from public.match_players
        where auth_uid = p_uid
    )
    select jsonb_build_object(
        'username', coalesce(nullif(btrim(coalesce(p_username, '')), ''), m.username, ''),
        'matches', t.matches,
        'escapes', t.escapes,
        'predictions', t.predictions,
        'correct', t.correct,
        'accuracy', round(t.correct::numeric / nullif(t.predictions, 0), 3),
        'attributes', coalesce(m.attributes, '{}'::jsonb),
        'style', m.style
    )
    from totals t
    left join public.player_models m on m.auth_uid = p_uid;
$$;

create or replace function public.leaderboard(p_limit integer default 10)
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
    with top as (
        select username, matches, attributes
        from public.player_models
        order by matches desc, username asc
        limit least(greatest(coalesce(p_limit, 10), 1), 100)
    )
    select coalesce(
        jsonb_agg(
            jsonb_build_object(
                'username', username,
                'matches', matches,
                'pattern', coalesce((attributes->>'pattern')::numeric, 0)
            )
            order by matches desc, username asc
        ),
        '[]'::jsonb
    )
    from top;
$$;

revoke all on function
    public.record_match(jsonb),
    public.match_history(text, integer),
    public.player_stats(text, text),
    public.leaderboard(integer)
from public, anon, authenticated;

grant execute on function
    public.record_match(jsonb),
    public.match_history(text, integer),
    public.player_stats(text, text),
    public.leaderboard(integer)
to service_role;
